import { readFileSync } from 'fs';
const envText = readFileSync('C:/Users/allan/projects/dailygiftshuffle/.env.local', 'utf8');
for (const line of envText.split('\n')) { const m = line.match(/^([^#=]+)=(.*)$/); if (m) process.env[m[1].trim()] = m[2].replace(/^"|"$/g,'').trim(); }
const REDIS_URL = process.env.UPSTASH_REDIS_REST_URL;
const REDIS_TOKEN = process.env.UPSTASH_REDIS_REST_TOKEN;
async function redisCmd(...args) {
  const res = await fetch(REDIS_URL, { method:'POST', headers:{ Authorization:'Bearer '+REDIS_TOKEN,'Content-Type':'application/json'}, body:JSON.stringify(args)});
  return (await res.json()).result;
}

const parsed = JSON.parse(await redisCmd('GET', 'admin:products'));
const now = new Date().toISOString();

// Fix 1: Jonathan Adler Marseilles Coasters — price display broken + still using Amazon image
const adlerIdx = parsed.findIndex(p => p.id === 'admin-1773608327652-sjz3x');
if (adlerIdx > -1) {
  parsed[adlerIdx].price = 60.22;
  parsed[adlerIdx].priceDisplay = '$60.22';
  parsed[adlerIdx].image = '/images/products/admin-1773608327652-sjz3x.jpg';
  parsed[adlerIdx].updatedAt = now;
  console.log('Fixed Adler: price=$60.22, image set to local path');
}

// Fix 2: Melissa & Doug Pattern Blocks — $0, no image generated by subagent
// ASIN B00006JZCG — Amazon shows ~$29.99 typical retail, 4.7 stars, 9300 reviews
const mdIdx = parsed.findIndex(p => p.id === 'admin-1773606530349-1v352');
if (mdIdx > -1) {
  parsed[mdIdx].price = 29.99;
  parsed[mdIdx].priceDisplay = '$29.99';
  parsed[mdIdx].rating = 4.7;
  parsed[mdIdx].reviewCount = 9300;
  parsed[mdIdx].image = '/images/products/admin-1773606530349-1v352.jpg';
  parsed[mdIdx].updatedAt = now;
  console.log('Fixed M&D: price=$29.99, rating=4.7 (9300 reviews)');
}

await redisCmd('SET', 'admin:products', JSON.stringify(parsed));
console.log('Redis patched.');

// Verify
const check = JSON.parse(await redisCmd('GET', 'admin:products'));
const stillBad = check.filter(p => p.name && p.name !== 'New Product' && (!p.price || p.price === 0));
console.log('Still missing price after fix:', stillBad.length);
